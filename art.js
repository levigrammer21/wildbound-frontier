function paper(width,height,label){
  const canvas=document.createElement('canvas'); canvas.width=width; canvas.height=height;
  canvas.className='pixel';canvas.setAttribute('role','img');canvas.setAttribute('aria-label',label);
  const c=canvas.getContext('2d');
  c.imageSmoothingEnabled=false;
  const rect=(color,x,y,w,h)=>{c.fillStyle=color;c.fillRect(x,y,w,h);};
  const poly=(color,pts)=>{
    c.fillStyle=color;c.beginPath();c.moveTo(pts[0][0],pts[0][1]);
    for(let i=1;i<pts.length;i++)c.lineTo(pts[i][0],pts[i][1]);c.closePath();c.fill();
  };
  return {canvas,c,rect,poly};
}
